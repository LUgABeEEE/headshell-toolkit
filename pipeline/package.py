"""Package stage: bundle the artifacts into a deliverable zip (MIT)."""
from __future__ import annotations
from dataclasses import dataclass
from pathlib import Path
import zipfile

from pipeline.contracts import Artifact, Manifest

NOTICE = """# NOTICE

Generated by HeadShell v2 pipeline. Check each artifact's license before redistribution.
GPL-derived research assets must not be shipped commercially.
"""


@dataclass(frozen=True)
class PackageConfig:
    include_stages: tuple[str, ...] = ("shell", "verify", "reconstruct", "design")
    write_notice: bool = True


def package_artifacts(manifest: Manifest, out_zip: str | Path,
                      config: PackageConfig | None = None) -> Artifact:
    """Zip the manifest's artifacts as a flat archive plus manifest.json and NOTICE.md.

    Only stages listed in config.include_stages are included, in that order.
    Files are stored under the artifact's stage name (missing files are skipped).
    Return an Artifact for the `package` stage.
    """
    cfg = config if config is not None else PackageConfig()
    out = Path(out_zip)
    out.parent.mkdir(parents=True, exist_ok=True)

    files = 0
    with zipfile.ZipFile(out, "w", compression=zipfile.ZIP_DEFLATED) as z:
        for stage in cfg.include_stages:
            artifact = manifest.artifacts.get(stage)
            if artifact is None:
                continue
            path = Path(artifact.path)
            if not path.is_file():
                continue
            z.write(path, arcname=f"{stage}/{path.name}")
            files += 1
        z.writestr("manifest.json", manifest.to_json().encode("utf-8"))
        if cfg.write_notice:
            z.writestr("NOTICE.md", NOTICE)

    return Artifact.create("package", out, {"stages": list(cfg.include_stages), "files": files})
